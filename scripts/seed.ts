interface WireEvent {
  event_id: string;
  session_id: string;
  name: string;
  step_id: string | null;
  client_ts: string;
  props: Record<string, unknown>;
}

/** An item to send plus the outcome the server must report for its first delivery. */
interface Entry {
  wire: unknown;
  expect: 'valid' | RejectReason;
}

const INVALID_KINDS: ((template: WireEvent) => unknown)[] = [
  (e) => ({ ...e, event_id: 'not-a-uuid' }),
  (e) => ({ ...e, name: undefined }),
  (e) => ({ ...e, props: 'answer_kind=number' }),
  (e) => ({ ...e, session_id: 12345 }),
  () => 'garbage',
  (e) => ({ ...e, step_id: { nested: true } }),
  () => null,
];

async function runSession(index: number, options: Options, tally: Tally): Promise<void> {
  const decide = decider(options.seed, index);
  const campaign = CAMPAIGNS[weightedIndex(decide('campaign'), CAMPAIGNS.map((c) => c.weight))];
  const client = new ApiClient(options.target);

  const query = campaign.utm ? `?${new URLSearchParams(campaign.utm)}` : '';
  const created = await client.post<SessionResponse>(`/api/session${query}`);
  tally.sessionsCreated++;
  increment(tally.versions, created.funnelVersion);
  increment(tally.variants, created.variant);
  increment(tally.campaigns, campaign.utm?.utm_campaign ?? '(none)');

  const config: MaterialisedConfig = created.config;
  const allowedNames = new Set((config.events?.allowed ?? []).map((e) => e.name));
  const nextEventId = eventIdGenerator(options.seed, created.sessionId);
  const entries: Entry[] = [];
  let clock = Date.now() - int(decide('clock-start'), 10 * 60, 6 * 3600) * 1000;
  const emit = (name: string, stepId: string | null, props: Record<string, unknown>) => {
    clock += int(decide('clock-tick', '', entries.length), 2, 9) * 1000;
    const wire: WireEvent = { event_id: nextEventId(), session_id: created.sessionId, name, step_id: stepId, client_ts: new Date(clock).toISOString(), props };
    // The generator does not filter by the allowed list; it predicts what the server will do.
    const expect = SERVER_ONLY_EVENTS.includes(name) ? 'server_only_event' : allowedNames.has(name) ? 'valid' : 'event_not_allowed';
    entries.push({ wire, expect });
  };

  let nav: NavigationResponse = created;
  const stepViewed = () => {
    const id = nav.currentStepId;
    if (!id) return;
    emit('step_viewed', id, {
      step_type: config.steps[id]?.type ?? 'unknown',
      visible_step_index: nav.visibleSteps.indexOf(id) + 1,
      visible_step_count: nav.visibleSteps.length,
    });
  };

  // Walk the funnel as the UI would: render, answer, render what the server returns.
  try {
    stepViewed();
    const visits = new Map<string, number>();
    let backs = 0;
    for (let guard = 0; guard < 200 && nav.currentStepId; guard++) {
      const stepId: string = nav.currentStepId;
      const step: Step = config.steps[stepId] ?? { id: stepId, type: 'unknown' };
      const visit = increment(visits, stepId).get(stepId)!;

      if (step.type === 'result') {
        tally.reachedResult++;
        emit('result_viewed', stepId, {});
        if (decide('cta', stepId, visit)() < CTA_PROBABILITY) {
          tally.ctaClicks++;
          const action = config.results[nav.resultId ?? '']?.cta?.action ?? 'expand_recommendation';
          emit('cta_clicked', stepId, { action });
          emit('recommendation_expanded', stepId, { action, source: 'cta' });
        }
        break;
      }

      if (decide('abandon', stepId, visit)() < abandonProbability(stepId)) {
        increment(tally.abandonedAt, stepId);
        break;
      }

      const value = pickAnswer(step, decide('answer', stepId, visit));
      if (stepId === 'work_mode' && typeof value === 'string') increment(tally.workModes, value);
      const answered = await client.post<NavigationResponse>('/api/session/answer', value === undefined ? { stepId } : { stepId, value });
      if (answered.currentStepId === stepId) throw new Error(`server did not advance from "${stepId}" (answer ${JSON.stringify(value)})`);
      if (step.type !== 'info') emit('answer_submitted', stepId, { answer_kind: step.type });
      emit('step_completed', stepId, { next_step_id: answered.currentStepId });
      nav = answered;
      stepViewed();

      const here = nav.currentStepId;
      if (here && config.steps[here]?.type !== 'result' && backs < MAX_BACKS_PER_SESSION && decide('back', stepId, visit)() < BACK_PROBABILITY) {
        const back = await client.post<NavigationResponse>('/api/session/back', { stepId: here });
        backs++;
        tally.backClicks++;
        emit('back_clicked', here, { destination_step_id: back.currentStepId });
        nav = back;
        stepViewed();
      }
    }
  } catch (err) {
    // Still send what was collected: the events up to the failure are real.
    tally.failures.push(`session #${index} (${created.sessionId}): ${(err as Error).message}`);
  }

  // Adversarial items mixed into the otherwise valid stream.
  const items: Entry[] = [...entries];
  const template = entries[0]?.wire as WireEvent | undefined;
  const insertAt = (entry: Entry, purpose: string) => items.splice(int(decide(purpose), 0, items.length), 0, entry);
  if (template) {
    if (index < 6 || decide('inject-invalid')() < 0.03) {
      insertAt({ wire: INVALID_KINDS[index % INVALID_KINDS.length]({ ...template, event_id: nextEventId() }), expect: 'invalid_shape' }, 'inject-invalid-at');
      tally.injectedInvalid++;
    }
    if (index % 50 === 0) {
      insertAt({ wire: { ...template, event_id: nextEventId(), name: 'session_started', step_id: null, props: {} }, expect: 'server_only_event' }, 'inject-server-only-at');
      tally.injectedServerOnly++;
    }
    if (index % 50 === 3) {
      const unknownSessionId = uuidFromBytes(Array.from({ length: 16 }, ((rng) => () => int(rng, 0, 255))(decide('unknown-session-id'))));
      insertAt({ wire: { ...template, event_id: nextEventId(), session_id: unknownSessionId }, expect: 'unknown_session' }, 'inject-unknown-session-at');
      tally.injectedUnknownSession++;
    }
  }

  // Split into 1–3 contiguous batches.
  const batchCount = Math.min(items.length, int(decide('batch-count'), 1, 3));
  const cuts = shuffle(decide('batch-cuts'), Array.from({ length: Math.max(0, items.length - 1) }, (_, i) => i + 1))
    .slice(0, batchCount - 1)
    .sort((a, b) => a - b);
  const bounds = [0, ...cuts, items.length];

  let firstBatch: { body: string; entries: Entry[]; results: EventResult[] } | null = null;
  for (let b = 0; b < bounds.length - 1; b++) {
    let batch = items.slice(bounds[b], bounds[b + 1]);

    const dupRng = decide('duplicate', '', b);
    if ((index === 0 && b === 0) || dupRng() < 0.2) {
      const candidates = batch.filter((entry) => entry.expect === 'valid');
      const copies = Math.min(candidates.length, int(dupRng, 1, 2));
      for (const original of shuffle(dupRng, candidates).slice(0, copies)) {
        batch.splice(int(dupRng, batch.indexOf(original) + 1, batch.length), 0, original);
        tally.injectedDuplicates++;
      }
    }

    const skewRng = decide('shuffle-skew', '', b);
    if ((index === 2 && b === 0) || skewRng() < 0.15) {
      const skewMs = (skewRng() < 0.5 ? 1 : -1) * int(skewRng, 1, 10) * 60_000;
      batch = shuffle(
        skewRng,
        batch.map((entry) => {
          if (entry.expect !== 'valid') return entry;
          const wire = entry.wire as WireEvent;
          return { ...entry, wire: { ...wire, client_ts: new Date(Date.parse(wire.client_ts) + skewMs).toISOString() } };
        }),
      );
      tally.shuffledBatches++;
    }

    const body = JSON.stringify({ events: batch.map((entry) => entry.wire) });
    const results = await deliver(options.target, body, batch, tally, `session #${index} batch ${b + 1}`);
    if (b === 0 && results) firstBatch = { body, entries: batch, results };
  }

  // One entire batch re-sent verbatim, as a client retrying after a timeout would.
  if (index === 0 && firstBatch) {
    const { body, entries: resent, results: original } = firstBatch;
    const results = await deliver(options.target, body, resent, tally, `session #${index} verbatim resend`);
    tally.resend.done = results !== null;
    results?.forEach((result, i) => {
      if (result.status === 'accepted') tally.resend.accepted++;
      const expected = original[i]?.status === 'rejected' ? 'rejected' : 'duplicate';
      if (result.status !== expected) tally.resend.unexpected++;
    });
  }
}

/** Sends one batch body, records what the server must report for it, then what it did report. */
async function deliver(target: string, body: string, batch: Entry[], tally: Tally, label: string): Promise<EventResult[] | null> {
  tally.batches++;
  tally.sent += batch.length;
  for (const entry of batch) {
    if (entry.expect !== 'valid') {
      increment(tally.expected.rejected, entry.expect);
      continue;
    }
    const id = (entry.wire as WireEvent).event_id.toLowerCase();
    if (tally.sentValidIds.has(id)) tally.expected.duplicate++;
    else {
      tally.sentValidIds.add(id);
      tally.expected.accepted++;
    }
  }

  const response = await fetch(new URL('/api/events', target), {
    method: 'POST',
    headers: { 'content-type': 'application/json', [SYNTHETIC_HEADER]: '1' },
    body,
  });
  const text = await response.text();
  if (response.status !== 200) {
    tally.non200.push(`${label}: HTTP ${response.status} ${text.slice(0, 200)}`);
    return null;
  }
  const { results } = JSON.parse(text) as EventBatchResponse;

  const aligned =
    results.length === batch.length &&
    results.every((result, i) => {
      const wire = batch[i].wire as { event_id?: unknown } | null;
      const sentId = typeof wire === 'object' && wire !== null && typeof wire.event_id === 'string' ? wire.event_id : null;
      return result.event_id === sentId;
    });
  if (!aligned) tally.misaligned.push(`${label}: ${results.length} results for ${batch.length} items`);
  for (const result of results) {
    if (result.status === 'accepted') tally.actual.accepted++;
    else if (result.status === 'duplicate') tally.actual.duplicate++;
    else increment(tally.actual.rejected, result.reason ?? '(no reason)');
  }
  return results;
}

