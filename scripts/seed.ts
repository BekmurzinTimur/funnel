const increment = <K>(map: Map<K, number>, key: K, by = 1) => map.set(key, (map.get(key) ?? 0) + by);

interface Outcomes {
  accepted: number;
  duplicate: number;
  rejected: Map<string, number>;
}
const newOutcomes = (): Outcomes => ({ accepted: 0, duplicate: 0, rejected: new Map(REJECT_REASONS.map((r) => [r, 0])) });

