export type Rng = () => number;

export function mulberry32(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function fnv1a(text: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

/** Decisions for session #index depend only on (seed, index). */
export const sessionRng = (seed: number, index: number): Rng => mulberry32(fnv1a(`session:${seed}:${index}`));

const int = (rng: Rng, min: number, max: number): number => min + Math.floor(rng() * (max - min + 1));
const chance = (rng: Rng, p: number): boolean => rng() < p;

function weightedIndex(rng: Rng, weights: number[]): number {
  const total = weights.reduce((sum, w) => sum + w, 0);
  let roll = rng() * total;
  for (let i = 0; i < weights.length; i++) {
    roll -= weights[i];
    if (roll < 0) return i;
  }
  return weights.length - 1;
}

function shuffle<T>(rng: Rng, items: T[]): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

/** RFC 4122 v4 UUID from 16 PRNG bytes (version nibble 4, variant bits 10xx). */
export function uuidFromBytes(bytes: number[]): string {
  const b = [...bytes];
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  const hex = b.map((x) => x.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`;
}

/**
 * Event-ID stream for one session. Two independent 32-bit streams feed the two
 * halves of the UUID, so IDs from different sessions only collide if both hashes do.
 */
export function eventIdGenerator(seed: number, sessionId: string): () => string {
  const high = mulberry32(fnv1a(`ids-high:${seed}:${sessionId}`));
  const low = mulberry32(fnv1a(`ids-low:${seed}:${sessionId}`));
  const byte = (rng: Rng) => Math.floor(rng() * 256);
  return () => uuidFromBytes([...Array.from({ length: 8 }, () => byte(high)), ...Array.from({ length: 8 }, () => byte(low))]);
}

