const formatMap = <K>(map: Map<K, number>): string =>
  map.size === 0 ? '(none)' : [...map].map(([k, v]) => `${String(k)}: ${v}`).join(', ');

async function main(): Promise<void> {
  let options: Options;
  try {
    options = parseArgs(process.argv.slice(2));
  } catch (err) {
    console.error((err as Error).message);
    process.exit(2);
  }

  console.log(`Seeding ${options.sessions} sessions against ${options.target} (seed ${options.seed}, concurrency ${options.concurrency})`);
  const tally = newTally();
  const started = Date.now();

  let next = 0;
  const worker = async () => {
    while (next < options.sessions) {
      const index = next++;
      try {
        await runSession(index, options, tally);
      } catch (err) {
        tally.failures.push(`session #${index}: ${(err as Error).message}`);
      }
      tally.sessionsCompleted++;
      if (tally.sessionsCompleted % 25 === 0) console.log(`  ${tally.sessionsCompleted} / ${options.sessions} sessions done`);
    }
  };
  await Promise.all(Array.from({ length: Math.min(options.concurrency, options.sessions) }, worker));

  const { actual, expected } = tally;
  const sum = (map: Map<string, number>) => [...map.values()].reduce((a, b) => a + b, 0);
  const pct = (n: number, d: number) => (d === 0 ? 'n/a' : `${((100 * n) / d).toFixed(1)}%`);

  console.log(`\nSummary (${((Date.now() - started) / 1000).toFixed(1)}s)`);
  console.log(`  sessions created    ${tally.sessionsCreated} / ${options.sessions}`);
  console.log(`  versions            ${formatMap(tally.versions)}`);
  console.log(`  variants            ${formatMap(tally.variants)}`);
  console.log(`  utm campaigns       ${formatMap(tally.campaigns)}`);
  console.log(`  work_mode answers   ${formatMap(tally.workModes)}`);
  console.log(`  reached result      ${tally.reachedResult} (${pct(tally.reachedResult, tally.sessionsCreated)})`);
  console.log(`  abandoned at        ${formatMap(tally.abandonedAt)}`);
  console.log(`  back navigations    ${tally.backClicks}`);
  console.log(`  cta clicks          ${tally.ctaClicks}`);
  console.log(`  batches sent        ${tally.batches} (${tally.shuffledBatches} shuffled + skewed, ${tally.resend.done ? 1 : 0} verbatim resend)`);
  console.log(`  events sent         ${tally.sent}`);
  console.log(`    accepted          ${actual.accepted} (expected ${expected.accepted})`);
  console.log(`    duplicate         ${actual.duplicate} (expected ${expected.duplicate})`);
  console.log(`    rejected          ${sum(actual.rejected)} (${formatMap(actual.rejected)})`);
  console.log(`      expected        ${sum(expected.rejected)} (${formatMap(expected.rejected)})`);
  console.log(
    `  injected            ${tally.injectedInvalid} invalid, ${tally.injectedDuplicates} duplicate copies, ` +
      `${tally.injectedServerOnly} client session_started, ${tally.injectedUnknownSession} unknown session`,
  );
  if (tally.failures.length) console.log(`  failures\n    ${tally.failures.slice(0, 20).join('\n    ')}`);
  if (tally.non200.length) console.log(`  non-200 /api/events\n    ${tally.non200.slice(0, 20).join('\n    ')}`);
  if (tally.misaligned.length) console.log(`  misaligned results\n    ${tally.misaligned.slice(0, 20).join('\n    ')}`);

  const reasons = new Set([...expected.rejected.keys(), ...actual.rejected.keys()]);
  const checks: [string, boolean][] = [
    [`sessions created === --sessions (${tally.sessionsCreated} / ${options.sessions})`, tally.sessionsCreated === options.sessions],
    [`no session API failures (${tally.failures.length})`, tally.failures.length === 0],
    [`every /api/events response was HTTP 200 (${tally.non200.length} not)`, tally.non200.length === 0],
    [`one result per item, in input order (${tally.misaligned.length} batches misaligned)`, tally.misaligned.length === 0],
    [
      `accepted + duplicate + rejected === sent (${actual.accepted} + ${actual.duplicate} + ${sum(actual.rejected)} = ${actual.accepted + actual.duplicate + sum(actual.rejected)} / ${tally.sent})`,
      actual.accepted + actual.duplicate + sum(actual.rejected) === tally.sent,
    ],
    [`accepted === expected (${actual.accepted} / ${expected.accepted})`, actual.accepted === expected.accepted],
    [`duplicate === expected (${actual.duplicate} / ${expected.duplicate})`, actual.duplicate === expected.duplicate],
    ...[...reasons].map((reason): [string, boolean] => [
      `rejected ${reason} === expected (${actual.rejected.get(reason) ?? 0} / ${expected.rejected.get(reason) ?? 0})`,
      (actual.rejected.get(reason) ?? 0) === (expected.rejected.get(reason) ?? 0),
    ]),
    [
      `verbatim resend produced 0 accepted (${tally.resend.accepted}), all duplicate or originally-rejected (${tally.resend.unexpected} unexpected)`,
      tally.resend.done && tally.resend.accepted === 0 && tally.resend.unexpected === 0,
    ],
  ];
  if (options.sessions >= 6) {
    checks.push([
      `adversarial cases present (${tally.injectedInvalid} invalid >= 5, ${tally.injectedServerOnly} session_started >= 1, ` +
        `${tally.injectedDuplicates} duplicate copies >= 1, ${tally.shuffledBatches} shuffled >= 1)`,
      tally.injectedInvalid >= 5 && tally.injectedServerOnly >= 1 && tally.injectedDuplicates >= 1 && tally.shuffledBatches >= 1,
    ]);
  }

  console.log('\nInvariants');
  for (const [label, ok] of checks) console.log(`  ${ok ? 'PASS' : 'FAIL'}  ${label}`);
  const failed = checks.filter(([, ok]) => !ok).length;
  console.log(failed ? `\nFAIL: ${failed} invariant(s) violated` : '\nPASS: all invariants hold');
  process.exit(failed ? 1 : 0);
}

