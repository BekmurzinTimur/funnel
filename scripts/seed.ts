class HttpError extends Error {}

/** One per simulated browser: carries that session's cookie jar. */
class ApiClient {
  private cookie: string | null = null;

  constructor(private readonly target: string) {}

  async post<T>(path: string, body?: unknown): Promise<T> {
    const headers: Record<string, string> = { [SYNTHETIC_HEADER]: '1' };
    if (this.cookie) headers.cookie = this.cookie;
    let payload: string | undefined;
    if (body !== undefined) {
      headers['content-type'] = 'application/json';
      payload = JSON.stringify(body);
    }
    const response = await fetch(new URL(path, this.target), { method: 'POST', headers, body: payload });
    const sessionCookie = response.headers
      .getSetCookie()
      .map((c) => c.split(';')[0].trim())
      .find((c) => c.startsWith(`${SESSION_COOKIE}=`));
    if (sessionCookie) this.cookie = sessionCookie;
    const text = await response.text();
    if (!response.ok) throw new HttpError(`POST ${path} -> ${response.status}: ${text.slice(0, 300)}`);
    return JSON.parse(text) as T;
  }
}

