/**
 * Synthetic traffic generator — SPEC §8.
 *
 *   npm run seed -- --sessions=150 --seed=42 --target=http://localhost:3000
 *
 * Drives the real HTTP API only (`POST /api/session`, `/api/session/answer`,
 * `/api/session/back`, `/api/events`). No database access, never touches admin
 * routes: sessions land on whatever version is active, and the materialised config
 * returned by `POST /api/session` is walked exactly as the UI would, so any version
 * works with no code change. Every session is created with the `x-synthetic: 1`
 * header, so it and its events are stored with is_synthetic = 1.
 *
 * Reproducibility. Every decision (campaign, answers, drop-off, back-navigation,
 * CTA clicks, batching, adversarial cases) comes from a mulberry32 PRNG derived from
 * `--seed` and the session's index, so decisions do not depend on concurrency.
 * Session IDs, however, are generated by the server, and variant assignment hashes
 * the session ID — so the A/B split (and therefore which step order each session
 * walks) varies slightly between runs even with the same seed.
 *
 * Event IDs are valid v4 UUIDs built from PRNG bytes, seeded from `--seed` plus the
 * server-issued session ID. Seeding them from `--seed` alone would make a second run
 * (e.g. after activating v3, §11) re-send the first run's event IDs, and every one of
 * them would be dropped as a duplicate.
 *
 * Adversarial cases, all present in a default run: duplicate event_ids within a
 * batch, one batch re-sent verbatim, shuffled batches with skewed client_ts,
 * schema-invalid items, a client-sent session_started, an unknown session, and
 * recommendation_expanded on CTA clicks (accepted on v3, rejected on v1).
 *
 * Exits 1 if any invariant in the summary fails.
 */
