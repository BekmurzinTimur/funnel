interface Options {
  sessions: number;
  seed: number;
  target: string;
  concurrency: number;
}

export function parseArgs(argv: string[]): Options {
  const options: Options = { sessions: 150, seed: 42, target: 'http://localhost:3000', concurrency: 6 };
  for (const arg of argv) {
    const match = /^--([a-z]+)=(.+)$/.exec(arg);
    if (!match) throw new Error(`Unrecognised argument "${arg}". Usage: --sessions=150 --seed=42 --target=http://localhost:3000`);
    const [, key, value] = match;
    if (key === 'target') {
      options.target = new URL(value).origin;
    } else if (key === 'sessions' || key === 'seed' || key === 'concurrency') {
      const n = Number(value);
      if (!Number.isInteger(n) || n < (key === 'seed' ? 0 : 1)) throw new Error(`--${key} must be an integer${key === 'seed' ? ' >= 0' : ' >= 1'}`);
      options[key] = n;
    } else {
      throw new Error(`Unknown option --${key}`);
    }
  }
  return options;
}

