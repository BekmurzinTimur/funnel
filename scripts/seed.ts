interface WireEvent {
  event_id: string;
  session_id: string;
  name: string;
  step_id: string | null;
  client_ts: string;
  props: Record<string, unknown>;
}

/** Items the walk produced that must come back accepted (first copy) / duplicate (later copies). */
const DUPLICATE_SAFE = new Set(['step_viewed', 'answer_submitted', 'step_completed', 'back_clicked', 'result_viewed', 'cta_clicked']);

const INVALID_KINDS: ((template: WireEvent) => unknown)[] = [
  (e) => ({ ...e, event_id: 'not-a-uuid' }),
  (e) => ({ ...e, name: undefined }),
  (e) => ({ ...e, props: 'answer_kind=number' }),
  (e) => ({ ...e, session_id: 12345 }),
  () => 'garbage',
  (e) => ({ ...e, step_id: { nested: true } }),
  () => null,
];

async function sendBatch(target: string, body: string): Promise<{ status: number; results: EventResult[] | null; text: string }> {
  const response = await fetch(new URL('/api/events', target), {
    method: 'POST',
    headers: { 'content-type': 'application/json', [SYNTHETIC_HEADER]: '1' },
    body,
  });
  const text = await response.text();
  if (response.status !== 200) return { status: response.status, results: null, text };
  return { status: 200, results: (JSON.parse(text) as EventBatchResponse).results, text };
}

async function runSession(index: number, options: Options, tally: Tally): Promise<void> {
  const rng = sessionRng(options.seed, index);
  const campaign = CAMPAIGNS[weightedIndex(rng, CAMPAIGNS.map((c) => c.weight))];
  const client = new ApiClient(options.target);

  const query = campaign.utm ? `?${new URLSearchParams(campaign.utm)}` : '';
  const created = await client.post<SessionResponse>(`/api/session${query}`);
  tally.sessionsCreated++;
  increment(tally.versions, created.funnelVersion);
  increment(tally.variants, created.variant);
  increment(tally.campaigns, campaign.utm?.utm_campaign ?? '(none)');

  const config: MaterialisedConfig = created.config;
  const nextEventId = eventIdGenerator(options.seed, created.sessionId);
  const events: WireEvent[] = [];
  let clock = Date.now() - int(rng, 10 * 60, 6 * 3600) * 1000;
  const emit = (name: string, stepId: string | null, props: Record<string, unknown>) => {
    clock += int(rng, 2, 9) * 1000;
    events.push({ event_id: nextEventId(), session_id: created.sessionId, name, step_id: stepId, client_ts: new Date(clock).toISOString(), props });
  };

  let nav: NavigationResponse = created;
  const stepViewed = () => {
    const id = nav.currentStepId;
    if (!id) return;
    emit('step_viewed', id, {
      step_type: config.steps[id]?.type ?? 'unknown',
      visible_step_index: nav.visibleSteps.indexOf(id) + 1,
      visible_step_count: nav.visibleSteps.length,
    });
  };

  // Walk the funnel as the UI would: render, answer, render what the server returns.
  try {
    stepViewed();
    let backs = 0;
    for (let guard = 0; guard < 200 && nav.currentStepId; guard++) {
      const stepId: string = nav.currentStepId;
      const step: Step = config.steps[stepId] ?? { id: stepId, type: 'unknown' };

      if (step.type === 'result') {
        tally.reachedResult++;
        emit('result_viewed', stepId, {});
        if (chance(rng, CTA_PROBABILITY)) {
          tally.ctaClicks++;
          const action = config.results[nav.resultId ?? '']?.cta?.action ?? 'expand_recommendation';
          emit('cta_clicked', stepId, { action });
          // Emitted regardless of the allowed list: accepted on v3, rejected on v1.
          emit('recommendation_expanded', stepId, { action, source: 'cta' });
        }
        break;
      }

      if (chance(rng, abandonProbability(stepId))) {
        increment(tally.abandonedAt, stepId);
        break;
      }

      const value = pickAnswer(step, rng);
      if (stepId === 'work_mode' && typeof value === 'string') increment(tally.workModes, value);
      const answered = await client.post<NavigationResponse>('/api/session/answer', value === undefined ? { stepId } : { stepId, value });
      if (answered.currentStepId === stepId) throw new Error(`server did not advance from "${stepId}" (answer ${JSON.stringify(value)})`);
      if (step.type !== 'info') emit('answer_submitted', stepId, { answer_kind: step.type });
      emit('step_completed', stepId, { next_step_id: answered.currentStepId });
      nav = answered;
      stepViewed();

      const here = nav.currentStepId;
      if (here && config.steps[here]?.type !== 'result' && backs < 3 && chance(rng, BACK_PROBABILITY)) {
        const back = await client.post<NavigationResponse>('/api/session/back', { stepId: here });
        backs++;
        tally.backClicks++;
        emit('back_clicked', here, { destination_step_id: back.currentStepId });
        nav = back;
        stepViewed();
      }
    }
  } catch (err) {
    // Still send what was collected: the events up to the failure are real.
    tally.failures.push(`session #${index} (${created.sessionId}): ${(err as Error).message}`);
  }

  // Adversarial items mixed into the otherwise valid stream.
  const items: unknown[] = [...events];
  const duplicateSafe = new Set<unknown>(events.filter((e) => DUPLICATE_SAFE.has(e.name)));
  const insertAt = (item: unknown) => items.splice(int(rng, 0, items.length), 0, item);
  const template = events[0];
  if (template) {
    if (index < 6 || chance(rng, 0.03)) {
      insertAt(INVALID_KINDS[index % INVALID_KINDS.length]({ ...template, event_id: nextEventId() }));
      tally.injectedInvalid++;
    }
    if (index % 50 === 0) {
      insertAt({ ...template, event_id: nextEventId(), name: 'session_started', step_id: null, props: {} });
      tally.injectedServerOnly++;
    }
    if (index % 50 === 3) {
      insertAt({ ...template, event_id: nextEventId(), session_id: uuidFromBytes(Array.from({ length: 16 }, () => int(rng, 0, 255))) });
      tally.injectedUnknownSession++;
    }
  }

  // Split into 1–3 contiguous batches.
  const batchCount = Math.min(items.length, int(rng, 1, 3));
  const cuts = shuffle(rng, Array.from({ length: Math.max(0, items.length - 1) }, (_, i) => i + 1))
    .slice(0, batchCount - 1)
    .sort((a, b) => a - b);
  const bounds = [0, ...cuts, items.length];

  let firstBatch: { body: string; results: EventResult[] } | null = null;
  for (let b = 0; b < bounds.length - 1; b++) {
    let batch = items.slice(bounds[b], bounds[b + 1]);

    if ((index === 0 && b === 0) || chance(rng, 0.2)) {
      const candidates = batch.filter((item) => duplicateSafe.has(item));
      const copies = Math.min(candidates.length, int(rng, 1, 2));
      for (const original of shuffle(rng, candidates).slice(0, copies)) {
        batch.splice(int(rng, batch.indexOf(original) + 1, batch.length), 0, original);
        tally.injectedDuplicates++;
      }
    }

    if ((index === 2 && b === 0) || chance(rng, 0.15)) {
      const skewMs = (chance(rng, 0.5) ? 1 : -1) * int(rng, 1, 10) * 60_000;
      batch = shuffle(
        rng,
        batch.map((item) => (duplicateSafe.has(item) ? { ...(item as WireEvent), client_ts: new Date(Date.parse((item as WireEvent).client_ts) + skewMs).toISOString() } : item)),
      );
      tally.shuffledBatches++;
    }

    const body = JSON.stringify({ events: batch });
    const results = await deliver(options.target, body, batch, tally, `session #${index} batch ${b + 1}`);
    if (b === 0 && results) firstBatch = { body, results };
  }

  // One entire batch re-sent verbatim, as a client retrying after a timeout would.
  if (index === 0 && firstBatch) {
    const parsed = (JSON.parse(firstBatch.body) as { events: unknown[] }).events;
    const results = await deliver(options.target, firstBatch.body, parsed, tally, `session #${index} verbatim resend`);
    tally.resend.done = results !== null;
    if (results) {
      results.forEach((result, i) => {
        if (result.status === 'accepted') tally.resend.accepted++;
        const expected = firstBatch.results[i]?.status === 'rejected' ? 'rejected' : 'duplicate';
        if (result.status !== expected) tally.resend.unexpected++;
      });
    }
  }
}

async function deliver(target: string, body: string, batch: unknown[], tally: Tally, label: string): Promise<EventResult[] | null> {
  tally.batches++;
  tally.sent += batch.length;
  const response = await sendBatch(target, body);
  if (response.status !== 200 || !response.results) {
    tally.non200.push(`${label}: HTTP ${response.status} ${response.text.slice(0, 200)}`);
    return null;
  }
  const { results } = response;
  const aligned =
    results.length === batch.length &&
    results.every((result, i) => {
      const item = batch[i] as { event_id?: unknown } | null;
      const sentId = typeof item === 'object' && item !== null && typeof item.event_id === 'string' ? item.event_id : null;
      return result.event_id === sentId;
    });
  if (!aligned) tally.misaligned.push(`${label}: ${results.length} results for ${batch.length} items`);
  for (const result of results) {
    if (result.status === 'accepted') tally.accepted++;
    else if (result.status === 'duplicate') tally.duplicate++;
    else increment(tally.rejected, result.reason ?? ('unknown' as RejectReason));
  }
  return results;
}

