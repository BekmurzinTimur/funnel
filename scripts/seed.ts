type Utm = { utm_source: string; utm_medium: string; utm_campaign: string };

const CAMPAIGNS: { weight: number; utm: Utm | null }[] = [
  { weight: 28, utm: { utm_source: 'google', utm_medium: 'cpc', utm_campaign: 'spring_launch' } },
  { weight: 20, utm: { utm_source: 'newsletter', utm_medium: 'email', utm_campaign: 'newsletter_q2' } },
  { weight: 14, utm: { utm_source: 'partner', utm_medium: 'referral', utm_campaign: 'partner_webinar' } },
  { weight: 20, utm: { utm_source: 'linkedin', utm_medium: 'paid_social', utm_campaign: 'linkedin_ops' } },
  { weight: 18, utm: null },
];

/** Single-select weights by step ID; unlisted steps/options are uniform. */
const SINGLE_SELECT_WEIGHTS: Record<string, Record<string, number>> = {
  work_mode: { remote: 40, hybrid: 40, office: 20 },
};

/** 5–12% per step, fixed per step ID so drop-off is spread across steps. */
export const abandonProbability = (stepId: string): number => 0.05 + (fnv1a(`abandon:${stepId}`) % 8) / 100;

const BACK_PROBABILITY = 0.12;
const CTA_PROBABILITY = 0.55;
const MAX_BACKS_PER_SESSION = 3;

export function pickAnswer(step: Step, rng: Rng): AnswerValue | undefined {
  const options = (step.input?.options ?? []).map((o) => o.value);
  switch (step.type) {
    case 'single-select': {
      if (options.length === 0) return undefined;
      const weights = options.map((o) => SINGLE_SELECT_WEIGHTS[step.id]?.[o] ?? 1);
      return options[weightedIndex(rng, weights)];
    }
    case 'multi-select': {
      const min = Math.max(1, step.validation?.minSelections ?? 1);
      const max = Math.max(min, Math.min(3, step.validation?.maxSelections ?? 3, options.length));
      const count = int(rng, min, max);
      const picked: string[] = [];
      if (options.includes('compliance') && rng() < 0.3) picked.push('compliance');
      const pool = options.filter((o) => o !== 'compliance');
      while (picked.length < count && pool.length > 0) picked.push(pool.splice(Math.floor(rng() * pool.length), 1)[0]);
      return picked;
    }
    case 'number': {
      const min = typeof step.input?.min === 'number' ? step.input.min : 0;
      const max = typeof step.input?.max === 'number' ? step.input.max : min + 10;
      const increment = typeof step.input?.step === 'number' && step.input.step > 0 ? step.input.step : 1;
      let lo = min;
      let hi = max;
      if (step.id === 'meeting_hours') {
        if (rng() < 0.35) lo = Math.max(min, 15);
        else hi = Math.min(max, 14);
      }
      const kLo = Math.ceil((lo - min) / increment);
      const kHi = Math.floor((hi - min) / increment);
      return kHi < kLo ? min : min + int(rng, kLo, kHi) * increment;
    }
    default:
      return undefined; // info, and unknown types rendered as skip-able placeholders
  }
}

